// Renders the reader into a container (used inside the modal on /app).
function legalView(which, onSwitch) {
  const doc = LEGAL[which];
  return [
    h('h2', { id: 'dlgTitle' }, 'قوانین و حریم خصوصی'),
    h('p', { class: 'sub' }, 'آخرین به‌روزرسانی: ', LEGAL_UPDATED),
    h('div', { class: 'fpills legal-tabs', role: 'group', 'aria-label': 'انتخاب متن' },
      Object.entries(LEGAL).map(([k, d]) => h('button', { type: 'button', 'aria-pressed': String(k === which), onclick: () => onSwitch(k) }, d.title))),
    h('div', { class: 'legal-body', tabindex: 0 },
      doc.sections.map(([title, paras]) => [h('h3', null, title), h('ul', null, paras.map(p => h('li', null, p)))])),
  ];
}
